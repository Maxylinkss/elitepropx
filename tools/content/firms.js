const byKey = new Map(firms.map((f) => [f.key, f]));

// Longest alias first so 'apex-trader-funding' wins over 'apex'.
const aliasList = firms
  .flatMap((f) => f.aliases.map((a) => ({ alias: a, firm: f })))
  .sort((a, b) => b.alias.length - a.alias.length);

function findFirm(text) {
  const t = String(text || '').toLowerCase();
  for (const { alias, firm } of aliasList) {
    if (t === alias || t.includes(alias)) return firm;
  }
  return null;
}

/** Strips a firm alias off the front of a slug and returns [firm, rest]. */
function splitFirm(text) {
  const t = String(text || '').toLowerCase();
  for (const { alias, firm } of aliasList) {
    if (t === alias) return [firm, ''];
    if (t.startsWith(alias + '-')) return [firm, t.slice(alias.length + 1)];
  }
  return [null, t];
}

function pairFromSlug(slug) {
  const s = slug.replace(/^\/blog\//, '').replace(/\.html$/, '');
  const parts = s.split('-vs-');
  if (parts.length !== 2) return null;
  const [a, b] = parts.map((p) => p.replace(/-comparison.*$/, '').replace(/-which-is-(easier|safer)$/, ''));
  const fa = findFirm(a);
  const fb = findFirm(b);
  if (!fa || !fb) return null;
  return [fa, fb];
}

module.exports = { firms, byKey, findFirm, splitFirm, pairFromSlug };
